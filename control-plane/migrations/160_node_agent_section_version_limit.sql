-- 160: предел колонки версии раздела agent (задача 001.29g; data-model.md §4.2.3 nodes).
-- Выдаваемый номер версии раздела agent — эпоха раскладки образа × 10 000 000 + колонка
-- agent_section_version (решение заказчика 2026-11-25): эпоха — номер набора правил, по которым
-- образ собирает раздел из источников; задача, переводящая поле раздела с заглушки на источник
-- (001.27, 001.36, 001.40), повышает эпоху, смена значения во время работы — колонку. Колонка не
-- больше 9 999 999 и в разряд эпохи не переходит: иначе номер одной эпохи совпал бы с номером
-- следующей. Номер и курсор контракта — int4, поэтому эпоха — от 1 до 213
-- (213 × 10 000 000 + 9 999 999 = 2 139 999 999 ≤ 2 147 483 647). Повышение сверх предела
-- отвергает CHECK, транзакция смены откатывается.
-- Ограничение — под своим именем, а не на месте ограничения 150: оно ключевой объект миграции для
-- самопроверки migrate (app/cli.py, key_object), и отметка 160 без него обнаруживается.
-- depends: 150_node_agent_section_version

SET LOCAL ROLE app_owner;
SET LOCAL search_path TO control_plane;

ALTER TABLE nodes
    ADD CONSTRAINT nodes_agent_section_version_range
    CHECK (agent_section_version BETWEEN 1 AND 9999999);
ALTER TABLE nodes DROP CONSTRAINT nodes_agent_section_version_check;
