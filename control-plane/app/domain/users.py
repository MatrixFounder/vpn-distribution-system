"""Доменный сервис учётных записей пользователей (UC-02, UC-15). Задача 001.13 — интерфейс с
заглушками, возвращающими фиксированные значения; логика (нормализация адреса §16.8, одноразовый
домен, уникальность, письмо подтверждения, ссылки восстановления ОВ-25, инвалидация сессий) —
задача 001.14."""

from __future__ import annotations

import uuid

UserId = uuid.UUID

# Идентификатор заглушки: любая операция «успешна» для этого пользователя (001.13).
STUB_USER_ID = uuid.UUID("00000000-0000-7000-8000-000000000001")


class UserService:
    """Регистрация, подтверждение адреса, аутентификация, восстановление пароля."""

    async def register(self, email: str, password: str, aup_version: str, lang: str) -> UserId:
        """Создать учётную запись «не подтверждена» и отправить письмо (UC-02 шаги 4–5) — 001.14.
        Заглушка: фиксированный идентификатор."""
        return STUB_USER_ID

    async def verify_email(self, token: str) -> None:
        """Подтвердить адрес по одноразовой ссылке (UC-02 шаг 6) — 001.14. Заглушка: успех."""

    async def authenticate(self, email: str, password: str) -> UserId | None:
        """Идентификатор пользователя по паре адрес/пароль или ``None`` — 001.14.
        Заглушка: фиксированный идентификатор."""
        return STUB_USER_ID

    async def request_reset(self, email: str) -> None:
        """Ссылка восстановления на адрес, если он зарегистрирован; ответ вызывающему одинаков
        в обоих случаях (UC-15 A1) — 001.14. Заглушка: успех."""

    async def confirm_reset(self, token: str, password: str) -> None:
        """Сменить пароль по ссылке, аннулировать её и все сессии (UC-15 шаги 4–5) — 001.14.
        Заглушка: успех."""
