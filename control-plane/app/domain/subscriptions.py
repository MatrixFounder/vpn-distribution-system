"""Подписка пользователя: состояние, период и переходы жизненного цикла (постановка §4.10,
§4.11 «Продление подписки», «Смена тарифа в середине периода», «Бонусный трафик»,
«Восстановление доступа»; data-model.md §4.2.4 ``subscriptions``, ``subscription_periods``,
``balance_entries``; UC-02, UC-05, UC-06; R-24, R-31).

Задача 001.21: ``SubscriptionService`` — операции жизненного цикла с фиксированными значениями,
чтобы кабинет (001.16), коды (001.20), лимиты (001.35) и очередь вызывали их до реализации.
Логика — 001.22: период в ``subscription_periods``, состояние в ``subscriptions``, журнал
``balance_entries`` и сброс порогов §4.17 новым периодом.

Что в заглушке настоящее — правила, а не значения:

- набор ``SubscriptionState`` — перечисление ``subscription_state`` базы целиком и в том же
  порядке (§4.2.4). Набор уже есть в базе и в OpenAPI кабинета, и третья копия с иным составом
  была бы дефектом: страж сверяет литералы с ``enum_range`` живой базы, а не со списком в тесте;
- набор ``PeriodSource`` — перечисление ``period_source`` (§4.2.4): чем заведён период — код,
  действие администратора или заказ (``orders`` — заглушка О-2). Это не источник записи баланса
  ``balance_source`` (``report | adjustment | bonus | late_report``) — на нём висит ``CHECK``
  обязательной причины, и в ``add_traffic`` речь именно о нём;
- **каждый переход публикует состав**: состояние подписки едет на ноды потоком состава §3.4, и
  переход, не разбудивший поток, не даёт ни отзыва в пределах Н-14, ни восстановления. Поэтому
  все шесть операций перехода вызывают ``CompositionService.publish_user`` — вызов настоящий и
  закреплён стражем, хотя сама публикация пока заглушка 001.28 (строки ``node_user_state`` —
  001.29). Постановку задачи ``composition.publish_user`` в транзакции перехода (outbox §5.4)
  вводит 001.22: до записи в базу публиковать нечего;
- ``remaining`` — «лимит периода − израсходовано», ``None`` при Unlimited (§4.11 «Типы
  лимитов»), а не самостоятельная колонка: в базе остатка нет. Фиксированные числа совпадают с
  ``accounting.stats.STUB_STATS``, и равенство закреплено стражем —
  ответ кабинета §4.2 собирается из этих заглушек сразу, и расхождение показало бы пользователю
  остаток, не сходящийся с его же статистикой.

Чего заглушка не делает: не читает и не пишет базу — пул хранится и передаётся потоку состава,
но ни одним запросом не пользуется (страж подставляет часового вместо пула); не заводит период,
не меняет состояние и не пишет ``balance_entries``. ``activate`` и ``renew`` возвращают один и тот
же ``STUB_PERIOD_ID`` при любых аргументах — это соглашение заглушки, а не правило §4.11.
"""

from __future__ import annotations

import uuid
from typing import Any, Literal

from app.domain.composition import CompositionService

# Перечисление ``subscription_state`` data-model.md §4.2.4 целиком: ``none`` — подписки не было,
# остальные четыре совпадают по имени с состоянием пользователя на ноде (§4.11) и едут в поток
# состава. ``removed`` из ``user_node_state`` сюда не входит — это состояние строки на ноде.
SubscriptionState = Literal["none", "active", "suspended_quota", "suspended_admin", "expired"]
# Перечисление ``period_source`` data-model.md §4.2.4: чем заведён период.
PeriodSource = Literal["redeem", "admin", "order"]
# ``subscription_periods.id`` (uuid v7): период — носитель срока, лимита и всех списаний.
PeriodId = uuid.UUID

# Фиксированные значения заглушки. Период, лимит и списанное — те же, что у
# ``accounting.stats.STUB_STATS``: кабинет собирает ответ §4.2 из обеих заглушек одновременно.
STUB_PERIOD_ID: PeriodId = uuid.UUID("00000000-0000-7000-8000-0000000000a1")
STUB_LIMIT_BYTES = 100 * 1024**3
STUB_USED_BILLABLE_BYTES = 20 * 1024**3
STUB_REMAINING_BYTES = STUB_LIMIT_BYTES - STUB_USED_BILLABLE_BYTES


class SubscriptionService:
    """Подписка поверх пула asyncpg. Заглушка 001.21: база не читается и не пишется, но переход
    состояния публикует состав — это обязанность каждой операции, а не деталь реализации."""

    def __init__(self, pool: Any, composition: CompositionService | None = None) -> None:
        self._pool = pool
        self._composition = composition or CompositionService(pool)

    async def activate(
        self, user_id: uuid.UUID, plan_id: uuid.UUID, source: PeriodSource
    ) -> PeriodId:
        """Активировать подписку: период тарифа от текущего момента, лимит — лимит тарифа,
        состояние ``active`` (§4.11 «Продление подписки», строка «Подписка истекла»; UC-02
        шаг 9). Возвращает идентификатор заведённого периода: бонус того же погашения кода
        (§4.14) пишется в ``balance_entries`` уже этого периода, и вызывающему (001.20) нужен
        его ключ. Заглушка — ``STUB_PERIOD_ID`` без записи; снимок ``device_limit`` из тарифа,
        сам период и credentials на доступных нодах — 001.22."""
        await self._composition.publish_user(user_id)
        return STUB_PERIOD_ID

    async def renew(self, user_id: uuid.UUID, source: PeriodSource) -> PeriodId:
        """Продлить подписку действующим тарифом: активная — новый период от даты окончания,
        истёкшая — от текущего момента; лимит равен лимиту тарифа, израсходованное обнуляется,
        неиспользованный остаток прежнего периода не переносится (§4.11 «Продление подписки»,
        обе строки таблицы; правило одно для администратора и для Redeem-кода). Возвращает
        идентификатор нового периода по той же причине, что и ``activate``. Заглушка —
        ``STUB_PERIOD_ID``."""
        await self._composition.publish_user(user_id)
        return STUB_PERIOD_ID

    async def change_plan(self, user_id: uuid.UUID, plan_id: uuid.UUID, actor: uuid.UUID) -> None:
        """Сменить тариф в середине периода: срок и лимит заменяются значениями нового тарифа,
        израсходованное переносится, прорации нет — смена не является продлением (§4.11 «Смена
        тарифа в середине периода»). ``actor`` — администратор: приёма платежей в MVP нет (О-2),
        самостоятельной смены тарифа тоже, а действие пишется в Audit Log (§4.16). Состав
        серверов при сужении групп доступа меняется в пределах Н-13 потоком состава (UC-06 A2).
        Заглушка — публикует состав и больше ничего."""
        await self._composition.publish_user(user_id)

    async def add_traffic(
        self, user_id: uuid.UUID, bytes: int, actor: uuid.UUID | None, reason: str | None
    ) -> None:
        """Начислить трафик текущему периоду: бонус Redeem- или Promo-кода (§4.14) либо
        увеличение лимита администратором (§4.11 «Восстановление доступа» — обе операции
        возвращают доступ исчерпавшему лимит, поэтому возврат из ``suspended_quota`` при
        положительном остатке делает 001.22 здесь же). ``actor`` — администратор либо ``None``
        (погашение кода пользователем); ``reason`` обязателен для корректировки администратора —
        ``CHECK (source <> 'adjustment' OR reason IS NOT NULL)`` §4.2.4. Заглушка — публикует
        состав и больше ничего.

        Имя операции: описание 001.20 называет её ``bonus``, 001.22 — ``add_traffic``; действует
        второе, и это один метод, а не два (расхождение записано примечанием в описание 001.20 —
        сам его текст, как подписанная история, не переписан).

        Куда ложится начисление, здесь не решается и передано в 001.22: §4.11 требует увеличить
        ``traffic_limit_bytes`` текущего периода, а §4.2.4 объявляет ``used_billable_bytes``
        денормализацией суммы ``balance_entries``, среди источников которой есть ``bonus``, —
        два разных места для одного начисления, и выбор меняет то, что кабинет показывает как
        «списано» (§4.12)."""
        await self._composition.publish_user(user_id)

    async def expire(self, user_id: uuid.UUID) -> None:
        """Перевести подписку в ``expired`` по истечении периода: пользователь удаляется из
        inbound на всех нодах, обменивающихся с Control Plane, в пределах Н-14 (§4.11 «Состояние
        пользователя на ноде»). Заглушка — публикует состав и больше ничего; задачу
        ``subscription.expire`` ставит планировщик (``jobs/handlers/subscriptions.py``)."""
        await self._composition.publish_user(user_id)

    async def set_state(self, user_id: uuid.UUID, state: SubscriptionState, reason: str) -> None:
        """Установить состояние подписки с причиной: ``suspended_quota`` при исчерпании лимита
        (§4.11 «Действие при исчерпании» — переводит ``LimitsService``, 001.35),
        ``suspended_admin`` — блокировка администратором, ``active`` — восстановление. Колонки
        причины у ``subscriptions`` нет (только ``state`` и ``state_changed_at``): причина уходит
        в Audit Log (§4.16) и в поле ``reason`` ответа кабинета (§4.2, UC-16 A1). Заглушка —
        публикует состав и больше ничего."""
        await self._composition.publish_user(user_id)

    async def remaining(self, user_id: uuid.UUID) -> int | None:
        """Остаток лимита текущего периода в единицах списания: лимит минус израсходованное,
        но не меньше нуля — разность бывает отрицательной, потому что списание за перерасход
        ограничено Н-17б (``Н-17 × traffic_multiplier`` ноды), а ``remaining`` кабинета и
        статистики объявлены ``ge=0``. Перерасход ноды без связи ограничен не этим, а грантом
        Н-17в. ``None`` — это Unlimited (``traffic_limit_bytes`` NULL, §4.11 «Типы лимитов»),
        а не «неизвестно».
        Чтение состояния состав не публикует. Заглушка — ``STUB_REMAINING_BYTES``."""
        return STUB_REMAINING_BYTES
